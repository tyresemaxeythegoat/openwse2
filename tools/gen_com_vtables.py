"""Generates engine/include/wse/recomp/com_vtables.h: the method names, in vtable order, of the
COM interfaces the R4 recording D3D9 / D3DX / DirectInput stubs implement
(`docs/RECOMP_PLAN.md` "R4 design").

Translated code calls COM methods by vtable slot, so the order must be exact. The order is read
from the mingw-w64 headers that ship with Zig (`lib/libc/include/any-windows-any`), which spell out
every inherited method inside each interface block. Only method names are emitted.

    python tools/gen_com_vtables.py [--include <mingw include dir>] [--check]

`--check` compares with the committed header instead of writing it. Never hand-edit the output.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'engine/include/wse/recomp/com_vtables.h'

# Interface -> header, plus counts the output must have (a parse error must not change a vtable).
INTERFACES = [
    ('IDirect3D9', 'd3d9.h', 17),
    ('IDirect3DDevice9', 'd3d9.h', 119),
    ('IDirect3DSwapChain9', 'd3d9.h', None),
    ('IDirect3DResource9', 'd3d9.h', None),
    ('IDirect3DBaseTexture9', 'd3d9.h', None),
    ('IDirect3DTexture9', 'd3d9.h', None),
    ('IDirect3DCubeTexture9', 'd3d9.h', None),
    ('IDirect3DVolumeTexture9', 'd3d9.h', None),
    ('IDirect3DSurface9', 'd3d9.h', None),
    ('IDirect3DVolume9', 'd3d9.h', None),
    ('IDirect3DVertexBuffer9', 'd3d9.h', None),
    ('IDirect3DIndexBuffer9', 'd3d9.h', None),
    ('IDirect3DVertexDeclaration9', 'd3d9.h', None),
    ('IDirect3DVertexShader9', 'd3d9.h', None),
    ('IDirect3DPixelShader9', 'd3d9.h', None),
    ('IDirect3DStateBlock9', 'd3d9.h', None),
    ('IDirect3DQuery9', 'd3d9.h', None),
    ('ID3DXBuffer', 'd3dx9core.h', None),
    ('ID3DXEffectPool', 'd3dx9effect.h', None),
    ('ID3DXEffect', 'd3dx9effect.h', None),
    ('IDirectInput8A', 'dinput.h', None),
    ('IDirectInput8W', 'dinput.h', None),
    ('IDirectInputDevice8A', 'dinput.h', None),
    ('IDirectInputDevice8W', 'dinput.h', None),
]


def find_include(arg):
    if arg:
        return pathlib.Path(arg)
    try:
        import ziglang  # the pip package that provides zig on the Windows host
        return pathlib.Path(ziglang.__file__).parent / 'lib/libc/include/any-windows-any'
    except ImportError:
        sys.exit('pass --include <mingw-w64 include dir> (no ziglang package found)')


def methods_of(text, name):
    m = re.search(r'DECLARE_INTERFACE_(?:IID_)?\(\s*' + re.escape(name) + r'\s*,[^)]*\)\s*\{', text)
    if not m:
        return None
    body = []
    depth = 1
    i = m.end()
    while depth > 0 and i < len(text):
        c = text[i]
        depth += c == '{'
        depth -= c == '}'
        body.append(c)
        i += 1
    block = re.sub(r'/\*.*?\*/', '', ''.join(body), flags=re.S)
    return re.findall(r'STDMETHOD(?:_\s*\([^,]+,\s*(\w+)\s*\)|\s*\(\s*(\w+)\s*\))', block)


def generate(include):
    lines = [
        '// Generated by tools/gen_com_vtables.py from the mingw-w64 headers (method names only, in',
        '// vtable order). Never hand-edit: rerun the generator. Used by the R4 recording D3D9, D3DX and',
        '// DirectInput stubs (`docs/RECOMP_PLAN.md` "R4 design").',
        '',
        '#pragma once',
        '',
        '#include <cstddef>',
        '',
        'namespace wse::recomp::com {',
        '',
        'struct Interface {',
        '    const char* name;',
        '    const char* const* methods;',
        '    std::size_t count;',
        '    unsigned char iid[16];  // IID_<name> as stored in memory (Data1-3 little-endian)',
        '};',
        '',
    ]
    for name, header, expect in INTERFACES:
        text = (include / header).read_text(encoding='utf-8', errors='replace')
        found = methods_of(text, name)
        if not found:
            sys.exit(f'{name}: not found in {header}')
        names = [a or b for a, b in found]
        if names[:3] != ['QueryInterface', 'AddRef', 'Release']:
            sys.exit(f'{name}: does not start with the IUnknown methods: {names[:3]}')
        if expect is not None and len(names) != expect:
            sys.exit(f'{name}: {len(names)} methods, expected {expect}')
        lines.append(f'inline constexpr const char* k{name}Methods[] = {{')
        for k in range(0, len(names), 4):
            lines.append('    ' + ' '.join(f'"{n}",' for n in names[k:k + 4]))
        lines.append('};')
        g = re.search(r'DEFINE_GUID\(\s*IID_' + re.escape(name) + r'\s*,([^)]*)\)', text)
        if not g:
            sys.exit(f'{name}: no IID_{name} in {header}')
        parts = [int(p.strip(), 16) for p in g.group(1).split(',')]
        iid = list(parts[0].to_bytes(4, 'little')) + list(parts[1].to_bytes(2, 'little')) + list(parts[2].to_bytes(2, 'little')) + parts[3:]
        if len(iid) != 16:
            sys.exit(f'{name}: malformed IID')
        iid_text = ', '.join(f'0x{b:02x}' for b in iid)
        lines.append(f'inline constexpr Interface k{name}{{"{name}", k{name}Methods, {len(names)}, {{{iid_text}}}}};')
        lines.append('')
    lines.append('}  // namespace wse::recomp::com')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--include')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    out = generate(find_include(args.include))
    if args.check:
        if OUT.read_text(encoding='utf-8') != out:
            sys.exit('com_vtables.h is out of date: rerun tools/gen_com_vtables.py')
        print('com_vtables.h is up to date')
        return
    OUT.write_text(out, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
