#!/usr/bin/env python3
"""Hardware differential for lifter operand widths and flag edges.

Synthesizes `instruction; ret` functions, lifts them with proof/lift.py, then
runs every vector on the host CPU (hw_x86.S) and through the lifted C. Covers
8/16/32/64-bit shifts, 2-operand imul, 32-bit cmovcc, and movd/movq between
GPRs and XMM.

Usage:
    python flagdiff.py --zig path\\to\\zig.exe
"""
import argparse
import os
import random
import subprocess
import sys

import capstone

import lift

CF, PF, AF, ZF, SF, OF = 1, 4, 0x10, 0x40, 0x80, 0x800

# name, bytes (without ret), kind, width, vector count
CASES = [
    ("sar8_cl",  "d2f8",       "shift", 8,  600),
    ("sar16_cl", "66d3f8",     "shift", 16, 600),
    ("sar32_cl", "d3f8",       "shift", 32, 800),
    ("sar64_cl", "48d3f8",     "shift", 64, 600),
    ("sar32_31", "c1f81f",     "shift", 32, 200),
    ("shl8_cl",  "d2e0",       "shift", 8,  800),
    ("shl16_cl", "66d3e0",     "shift", 16, 800),
    ("shl32_cl", "d3e0",       "shift", 32, 800),
    ("shl64_cl", "48d3e0",     "shift", 64, 800),
    ("shr8_cl",  "d2e8",       "shift", 8,  800),
    ("shr16_cl", "66d3e8",     "shift", 16, 800),
    ("shr32_cl", "d3e8",       "shift", 32, 800),
    ("shr64_cl", "48d3e8",     "shift", 64, 800),
    ("imul16",   "660fafc1",   "imul",  16, 1200),
    ("imul32",   "0fafc1",     "imul",  32, 1600),
    ("cmovne32", "0f45c1",     "cmov",  32, 800),
    ("cmovae32", "0f43c1",     "cmov",  32, 800),
    ("movd_xmm_eax",  "660f6ec0",   "xmm", 32, 200),
    ("movq_xmm_rax",  "66480f6ec0", "xmm", 64, 200),
    ("movq_xmm_xmm",  "f30f7ec8",   "xmm", 64, 200),
]

KIND = {"shift": 0, "imul": 1, "cmov": 2, "xmm": 3}
BASE_RVA = 0x1000
STRIDE = 0x10

EDGES = [
    0, 1, 2, 3, 7, 8, 15, 16, 31, 32, 33, 63, 64, 95, 127, 128, 129,
    255, 256, 0x7F, 0x80, 0xFF, 0x100, 0x7FFF, 0x8000, 0xFFFF, 0x10000,
    0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x100000000,
    0x7FFFFFFFFFFFFFFF, 0x8000000000000000, 0xFFFFFFFFFFFFFFFF,
    0xAAAAAAAAAAAAAAAA, 0x5555555555555555,
]

FLAG_SETS = [0, CF, PF, AF, ZF, SF, OF, CF | ZF, SF | OF, CF | PF | AF | ZF | SF | OF]


def gen_vectors():
    rnd = random.Random(0xF1A6)
    rows = []
    for idx, (name, hx, kind, width, n) in enumerate(CASES):
        if kind == "shift":
            for k in range(n):
                a = EDGES[k % len(EDGES)] if k < len(EDGES) * 4 else rnd.getrandbits(64)
                if k % 3 == 1:
                    a &= (1 << width) - 1
                cnt = k % 64 if k < 256 else rnd.randrange(64)
                rows.append((idx, a, cnt, 0))
            # Immediate form: only CL-encoded cases in the table use b; for
            # sar32_31 the instruction has no operand, b is irrelevant.
        elif kind == "imul":
            mask = (1 << width) - 1
            for k in range(n):
                if k < len(EDGES) * 4:
                    a = EDGES[k % len(EDGES)] & mask
                    b = EDGES[(k * 7 + 3) % len(EDGES)] & mask
                else:
                    a = rnd.getrandbits(width) & mask
                    b = rnd.getrandbits(width) & mask
                rows.append((idx, a, b, rnd.choice(FLAG_SETS)))
        elif kind == "cmov":
            for k in range(n):
                a = rnd.getrandbits(64)
                b = rnd.getrandbits(64)
                if k < len(EDGES) * 4:
                    a = EDGES[k % len(EDGES)]
                    b = EDGES[(k * 5 + 1) % len(EDGES)]
                    fl = FLAG_SETS[k % len(FLAG_SETS)]
                else:
                    fl = rnd.choice(FLAG_SETS)
                rows.append((idx, a, b, fl))
        else:  # xmm
            for k in range(n):
                a = EDGES[k % len(EDGES)] if k < len(EDGES) * 4 else rnd.getrandbits(64)
                rows.append((idx, a, rnd.getrandbits(64), rnd.choice(FLAG_SETS)))
    return rows


def disasm_one(code, rva):
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    md.detail = True
    insns = list(md.disasm(code, rva))
    if sum(i.size for i in insns) != len(code):
        raise SystemExit("disassembly did not consume 0x%X" % rva)
    return insns


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zig", required=True)
    ap.add_argument("--workdir", default="work_flagdiff")
    args = ap.parse_args()

    os.makedirs(args.workdir, exist_ok=True)
    os.environ.setdefault("ZIG_GLOBAL_CACHE_DIR", os.path.join(os.environ.get("TEMP", "."), "z", "cache"))
    os.environ.setdefault("ZIG_LOCAL_CACHE_DIR", os.path.join(os.environ.get("TEMP", "."), "z", "lcache"))

    lifted = ["/* Generated by flagdiff.py. Do not hand-edit. */", ""]
    decls = []
    code_arrays = []
    table = []

    for idx, (name, hx, kind, width, _n) in enumerate(CASES):
        rva = BASE_RVA + idx * STRIDE
        raw = bytes.fromhex(hx) + b"\xC3"
        insns = disasm_one(raw, rva)
        lf = lift.Lifter(insns, rva, rva + len(raw))
        text = lf.lift()
        if lf.unsupported:
            raise SystemExit("%s: lifter reported unsupported instruction" % name)
        lifted.append("/* %s: %s */" % (name, insns[0].mnemonic + " " + insns[0].op_str))
        lifted.append(text)

        decls.append("uint32_t f_%X(CPU *c);" % rva)
        arr = "code_%d" % idx
        code_arrays.append("static const unsigned char %s[] = { %s };" % (
            arr, ", ".join("0x%02X" % b for b in raw)))
        table.append('    { "%s", f_%X, %s, %d, %d, %d },' % (
            name, rva, arr, len(raw), KIND[kind], width))

    header = []
    header.append("/* Generated by flagdiff.py. Do not hand-edit. */")
    header.append("#define MAX_CASES %d" % len(CASES))
    header.extend(decls)
    header.append("")
    header.extend(code_arrays)
    header.append("")
    header.append("typedef struct {")
    header.append("    const char *name;")
    header.append("    uint32_t (*fn)(CPU *c);")
    header.append("    const unsigned char *code;")
    header.append("    unsigned code_len;")
    header.append("    unsigned kind;")
    header.append("    unsigned width;")
    header.append("} Case;")
    header.append("")
    header.append("static const Case cases[] = {")
    header.extend(table)
    header.append("};")

    with open(os.path.join(args.workdir, "flagdiff_lifted.c"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lifted) + "\n")
    with open(os.path.join(args.workdir, "flagdiff_cases.h"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(header) + "\n")

    rows = gen_vectors()
    vec = os.path.join(args.workdir, "vectors.txt")
    with open(vec, "w", encoding="ascii", newline="\n") as f:
        for idx, a, b, fl in rows:
            f.write("%d %x %x %x\n" % (idx, a, b, fl))

    exe = os.path.abspath(os.path.join(args.workdir, "flagdiff.exe"))
    cmd = [
        args.zig, "cc", "-target", "x86_64-windows-gnu", "-O1", "-fno-strict-aliasing",
        "-I.", "-I" + os.path.abspath(args.workdir), "-o", exe,
        "flagdiff_main.c", "hw_x86.S", os.path.join(args.workdir, "flagdiff_lifted.c"),
    ]
    print("build:", " ".join(cmd))
    subprocess.run(cmd, check=True)
    run = subprocess.run([exe, os.path.abspath(vec)])
    return run.returncode


if __name__ == "__main__":
    sys.exit(main())
